"""Generates the built-in historic ΔT table from USNO historic_deltat.data.

Usage:
    Scripts/generate-historic-delta-t.py historic_deltat.data \
        > Sources/Astronomia/Timescales/HistoricDeltaTEntries.swift

The file is available from https://maia.usno.navy.mil/ser7/historic_deltat.data.
Each data row is: decimal year, TDT − UT1 (s), its error (s), LOD (ms), its error (ms).
The LOD columns are not used.

Each decimal year is taken as calendar-based in TT, as JulianDate(decimalYear:) does: the
fraction is the fraction of the Gregorian calendar year elapsed, so 1657.5 is noon on
July 2, 1657. The date is converted exactly and written as a Julian day number and a
fraction from noon.
"""

import datetime
import hashlib
import math
import re
import sys
from fractions import Fraction

SOURCE_URL = "https://maia.usno.navy.mil/ser7/historic_deltat.data"
NUMBER = re.compile(r"^[+-]?(\d+\.?\d*|\.\d+)$")
# Julian day number of 0001-01-01 minus its proleptic Gregorian ordinal
ORDINAL_TO_JDN = 1_721_425


def swift_literal(token: str, line_number: int) -> str:
	"""Returns `token` as a Swift floating-point literal, keeping its digits."""
	if not NUMBER.match(token):
		sys.exit(f"line {line_number}: not a number: {token!r}")
	sign = "-" if token.startswith("-") else ""
	digits = token.lstrip("+-")
	if digits.startswith("."):
		digits = "0" + digits
	if digits.endswith("."):
		digits += "0"
	return sign + digits


def julian_date(decimal_year: str, line_number: int) -> tuple[int, Fraction]:
	"""Returns the Julian day number and fraction from noon of a calendar-based decimal year."""
	y = Fraction(decimal_year)
	year = math.floor(y)
	if year < 1583:
		sys.exit(f"line {line_number}: {decimal_year} is before the Gregorian calendar")
	start = datetime.date(year, 1, 1)
	days_in_year = (datetime.date(year + 1, 1, 1) - start).days
	days = (y - year) * days_in_year
	day = math.floor(days)
	from_noon = (days - day) - Fraction(1, 2)
	# The fraction must be exact in binary to match JulianDate(decimalYear:).
	if from_noon.denominator & (from_noon.denominator - 1):
		sys.exit(f"line {line_number}: {decimal_year} is not an exact binary fraction of a day")
	return start.toordinal() + ORDINAL_TO_JDN + day, from_noon


def parse(text: str) -> list[tuple[str, int, Fraction, str, str]]:
	"""Returns the year, date, ΔT, and uncertainty of each data row, checking the rows."""
	rows = []
	previous_year = -math.inf
	saw_header = False
	for line_number, line in enumerate(text.splitlines(), start=1):
		fields = line.split()
		if not fields:
			continue
		if not saw_header:
			# The first line names the columns; the second gives their units.
			if fields[0] == "Year" and "TDT-UT1" in fields:
				saw_header = True
				continue
			sys.exit(f"line {line_number}: expected the column header, found {line!r}")
		if fields[0].startswith("("):
			continue
		if len(fields) != 5:
			sys.exit(f"line {line_number}: expected 5 columns, found {len(fields)}")
		year, delta_t, uncertainty = (swift_literal(token, line_number) for token in fields[:3])
		if float(year) <= previous_year:
			sys.exit(f"line {line_number}: year {year} does not increase")
		if float(uncertainty) < 0:
			sys.exit(f"line {line_number}: negative uncertainty {uncertainty}")
		previous_year = float(year)
		jdn, from_noon = julian_date(year, line_number)
		rows.append((year, jdn, from_noon, delta_t, uncertainty))
	if len(rows) < 2:
		sys.exit("expected at least two data rows")
	return rows


def generate(data: bytes) -> str:
	rows = parse(data.decode("ascii"))
	digest = hashlib.sha256(data).hexdigest()
	width = max(len(delta_t) for _, _, _, delta_t, _ in rows)
	lines = [
		"//",
		"// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>",
		"// SPDX-License-Identifier: MIT",
		"//",
		"// Part of https://github.com/sbooth/Astronomia",
		"//",
		"",
		"// Generated by Scripts/generate-historic-delta-t.py. Do not edit.",
		f"// Source: {SOURCE_URL}",
		f"// SHA-256: {digest}",
		"",
		f"/// ΔT = TT - UT1 and its uncertainty, in seconds, from {rows[0][0]} to {rows[-1][0]}.",
		"///",
		"/// Each entry's comment gives the decimal year in the source file.",
		"let historicDeltaTEntries: [DeltaTTable.Entry] = [",
	]
	for year, jdn, from_noon, delta_t, uncertainty in rows:
		tt = f"JulianDate(uncheckedJulianDayNumber: {jdn:_}, fractionFromNoon: {float(from_noon)!r:>4})"
		lines.append(
			f"\t.init(tt: {tt}, deltaT: {(delta_t + ',').ljust(width + 1)} uncertainty: {uncertainty}), // {year}"
		)
	lines.append("]")
	return "\n".join(lines) + "\n"


def main() -> None:
	if len(sys.argv) != 2:
		sys.exit(__doc__)
	with open(sys.argv[1], "rb") as file:
		sys.stdout.write(generate(file.read()))


if __name__ == "__main__":
	main()
