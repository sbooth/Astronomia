"""Generates Swift source for Astronomia timescale data from published data files.

Each command reads a data file, checks it, and writes a Swift array of entries to standard
output. The array can be compiled into an app, so the data needs no parsing at run time.

Commands:

  historic-delta-t FILE
      USNO historic_deltat.data, as an array of DeltaTTable.Entry. Pass the array to
      DeltaTTable(entries:).

  modern-delta-t FILE
      USNO deltat.data, monthly ΔT from 1973, as an array of DeltaTTable.Entry. Pass the
      array to DeltaTTable(entries:).

  The ΔT commands write each date with JulianDate's internal unchecked initializer, so
  their output is for Astronomia's built-in tables.

  leap-seconds FILE
      The IERS/IETF leap-seconds.list, as an array of LeapSecondTable.LeapSecond with TAI - UTC
      in whole seconds from 1972, and the horizon: the UTC day on which the file expires, the
      first it does not cover. The file's SHA-1 hash is checked. Pass both to
      LeapSecondTable(leapSeconds:horizon:). Before 1972 the table uses the fixed rate entries
      of tai-utc.dat.

  finals FILE
      IERS finals2000A data (.all, .data, or .daily), as an array of
      EarthOrientationTable.Entry with the Bulletin A values of UT1 - UTC, polar motion, the
      celestial pole offsets, and the excess length of day. For IAU 1980 finals data, pass
      --ut1-only, since its nutation columns are not dX and dY. Pass the array to
      EarthOrientationTable(entries:leapSecondTable:). With --table, writes the table itself,
      built with the built-in leap seconds, so the entries are not kept after it is built.
      The values are written as private [Double] literals at file scope, which the compiler
      handles far better than an array of initializers, and the entries or table are built
      on first use. With --array, writes an array literal of initializers instead, one per
      row, which is easier to read but slow to compile for more than a few thousand rows.

Examples:

  # The built-in ΔT tables
  Scripts/generate-timescale-data.py historic-delta-t historic_deltat.data --spdx \\
      > Sources/Astronomia/Timescales/DeltaT/HistoricDeltaTEntries.swift
  Scripts/generate-timescale-data.py modern-delta-t deltat.data --spdx \\
      > Sources/Astronomia/Timescales/DeltaT/ModernDeltaTEntries.swift

  # The built-in leap seconds
  Scripts/generate-timescale-data.py leap-seconds leap-seconds.list --spdx --no-import \\
      > Sources/Astronomia/Timescales/LeapSeconds/BuiltInLeapSeconds.swift

  # Observations from 2000 on, without predictions, for use in an app
  Scripts/generate-timescale-data.py finals finals2000A.all --name finalsEntries \\
      --start 2000-01-01 --no-predictions > FinalsEntries.swift

  # A table ready to use in a UT1 context
  Scripts/generate-timescale-data.py finals finals2000A.all --table --name earthOrientation \\
      > EarthOrientation.swift

Run a command with --help for its options.
"""

import argparse
import datetime
import hashlib
import math
import os
import re
import sys
from fractions import Fraction

NUMBER = re.compile(r"^[+-]?(\d+\.?\d*|\.\d+)$")
# Julian day number of 0001-01-01 minus its proleptic Gregorian ordinal
ORDINAL_TO_JDN = 1_721_425
# Civil Julian day number of MJD 0, the day beginning at JD 2400000.5
MJD_TO_JDN = 2_400_001

SPDX_HEADER = [
	"//",
	"// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>",
	"// SPDX-License-Identifier: MIT",
	"//",
	"// Part of https://github.com/sbooth/Astronomia",
	"//",
	"",
]


class DataError(Exception):
	"""A problem with the input file, reported with its line number."""


def swift_literal(token: str, line_number: int) -> str:
	"""Returns `token` as a Swift floating-point literal, keeping its digits."""
	if not NUMBER.match(token):
		raise DataError(f"line {line_number}: not a number: {token!r}")
	sign = "-" if token.startswith("-") else ""
	digits = token.lstrip("+-")
	if digits.startswith("."):
		digits = "0" + digits
	if digits.endswith("."):
		digits += "0"
	return sign + digits


def civil_date(jdn: int) -> datetime.date:
	"""Returns the Gregorian date of a civil Julian day number."""
	return datetime.date.fromordinal(jdn - ORDINAL_TO_JDN)


def civil_jdn(date: datetime.date) -> int:
	"""Returns the civil Julian day number of a Gregorian date."""
	return date.toordinal() + ORDINAL_TO_JDN


def header(args: argparse.Namespace, command: str, data: bytes, source_url: str) -> list[str]:
	"""Returns the generated file's header lines."""
	lines = list(SPDX_HEADER) if args.spdx else []
	lines += [
		f"// Generated by Scripts/generate-timescale-data.py {command}. Do not edit.",
		f"// Source: {source_url}",
		f"// SHA-256: {hashlib.sha256(data).hexdigest()}",
		"",
	]
	return lines


def declaration(args: argparse.Namespace, type_name: str, initial: str = "[", name: str | None = None) -> str:
	"""Returns the declaration line of a constant of `type_name`, named `name` or args.name."""
	access = "" if args.access == "internal" else f"{args.access} "
	return f"{access}let {name or args.name}: {type_name} = {initial}"


# MARK: - historic-delta-t


def decimal_year_julian_date(decimal_year: str, line_number: int) -> tuple[int, Fraction]:
	"""Returns the Julian day number and fraction from noon of a calendar-based decimal year.

	The fraction is the fraction of the Gregorian calendar year elapsed, as for
	JulianDate(decimalYear:), so 1657.5 is noon on July 2, 1657.
	"""
	y = Fraction(decimal_year)
	year = math.floor(y)
	if year < 1583:
		raise DataError(f"line {line_number}: {decimal_year} is before the Gregorian calendar")
	start = datetime.date(year, 1, 1)
	days_in_year = (datetime.date(year + 1, 1, 1) - start).days
	days = (y - year) * days_in_year
	day = math.floor(days)
	from_noon = (days - day) - Fraction(1, 2)
	# The fraction must be exact in binary to match JulianDate(decimalYear:).
	if from_noon.denominator & (from_noon.denominator - 1):
		raise DataError(f"line {line_number}: {decimal_year} is not an exact binary fraction of a day")
	return civil_jdn(start) + day, from_noon


def historic_delta_t(args: argparse.Namespace, data: bytes) -> str:
	"""Each data row is: decimal year, TDT - UT1 (s), its error (s), LOD (ms), its error (ms).
	The LOD columns are not used."""
	rows = []
	previous_year = -math.inf
	saw_header = False
	for line_number, line in enumerate(data.decode("ascii").splitlines(), start=1):
		fields = line.split()
		if not fields:
			continue
		if not saw_header:
			# The first line names the columns; the second gives their units.
			if fields[0] == "Year" and "TDT-UT1" in fields:
				saw_header = True
				continue
			raise DataError(f"line {line_number}: expected the column header, found {line!r}")
		if fields[0].startswith("("):
			continue
		if len(fields) != 5:
			raise DataError(f"line {line_number}: expected 5 columns, found {len(fields)}")
		year, delta_t, uncertainty = (swift_literal(token, line_number) for token in fields[:3])
		if float(year) <= previous_year:
			raise DataError(f"line {line_number}: year {year} does not increase")
		if float(uncertainty) < 0:
			raise DataError(f"line {line_number}: negative uncertainty {uncertainty}")
		previous_year = float(year)
		jdn, from_noon = decimal_year_julian_date(year, line_number)
		rows.append((year, jdn, from_noon, delta_t, uncertainty))
	if len(rows) < 2:
		raise DataError("expected at least two data rows")

	width = max(len(delta_t) for _, _, _, delta_t, _ in rows)
	lines = header(args, "historic-delta-t", data, args.source_url)
	lines += [
		f"/// ΔT = TT - UT1 and its uncertainty, in seconds, from {rows[0][0]} to {rows[-1][0]}.",
		"///",
		"/// Each entry's comment gives the decimal year in the source file.",
		declaration(args, "[DeltaTTable.Entry]"),
	]
	for year, jdn, from_noon, delta_t, uncertainty in rows:
		tt = f"JulianDate(uncheckedJulianDayNumber: {jdn:_}, fractionFromNoon: {float(from_noon)!r:>4})"
		lines.append(f"\t.init(tt: {tt}, deltaT: {(delta_t + ',').ljust(width + 1)} uncertainty: {uncertainty}), // {year}")
	lines.append("]")
	return "\n".join(lines) + "\n"


# MARK: - modern-delta-t


def modern_delta_t(args: argparse.Namespace, data: bytes) -> str:
	"""Each row is: year, month, day, and ΔT = TT - UT1 in seconds, for 0h on the date. The
	date is taken as TT; reading it as UT1 instead moves it by about a minute, which changes
	ΔT by under a microsecond."""
	rows = []
	previous_day = None
	for line_number, line in enumerate(data.decode("ascii").splitlines(), start=1):
		fields = line.split()
		if not fields:
			continue
		if len(fields) != 4:
			raise DataError(f"line {line_number}: expected 4 columns, found {len(fields)}")
		try:
			date = datetime.date(int(fields[0]), int(fields[1]), int(fields[2]))
		except ValueError:
			raise DataError(f"line {line_number}: invalid date {' '.join(fields[:3])!r}") from None
		delta_t = swift_literal(fields[3], line_number)
		day = civil_jdn(date)
		if previous_day is not None and day <= previous_day:
			raise DataError(f"line {line_number}: {date} does not increase")
		previous_day = day
		rows.append((date, day, delta_t))
	if len(rows) < 2:
		raise DataError("expected at least two data rows")

	width = max(len(delta_t) for _, _, delta_t in rows)
	lines = header(args, "modern-delta-t", data, args.source_url)
	lines += [
		f"/// ΔT = TT - UT1, in seconds, at 0h TT from {rows[0][0]} to {rows[-1][0]}.",
		"///",
		"/// Each entry's comment gives the date in the source file.",
		declaration(args, "[DeltaTTable.Entry]"),
	]
	for date, day, delta_t in rows:
		tt = f"JulianDate(uncheckedJulianDayNumber: {day:_}, fractionFromNoon: -0.5)"
		lines.append(f"\t.init(tt: {tt}, deltaT: {(delta_t + '),').ljust(width + 2)} // {date}")
	lines.append("]")
	return "\n".join(lines) + "\n"


# MARK: - leap-seconds

# Civil Julian day number of the NTP epoch, 1900-01-01
NTP_TO_JDN = 2_415_021
# Civil Julian day number of 1972-01-01, from which TAI - UTC is a whole number of seconds
JDN_1972 = 2_441_318


def leap_seconds(args: argparse.Namespace, data: bytes) -> str:
	"""Reads the IERS/IETF leap-seconds.list: lines of NTP seconds since 1900-01-01 and TAI - UTC
	in seconds, with the last update in the #$ line, the expiry in the #@ line, and a SHA-1
	hash of both and the data in the #h line. The data must start at 1972-01-01 with 10 s, and
	each later line must change TAI - UTC by one second on the first day of a month."""
	updated = expires = digest = None
	rows = []
	for line_number, line in enumerate(data.decode("ascii").splitlines(), start=1):
		if line.startswith("#$"):
			updated = line[2:].split()[0]
		elif line.startswith("#@"):
			expires = line[2:].split()[0]
		elif line.startswith("#h"):
			digest = "".join(word.rjust(8, "0") for word in line[2:].split())
		elif line.startswith("#") or not line.strip():
			continue
		else:
			fields = line.split("#")[0].split()
			if len(fields) != 2 or not all(field.isdigit() for field in fields):
				raise DataError(f"line {line_number}: expected NTP seconds and TAI - UTC, found {line!r}")
			rows.append((line_number, fields[0], fields[1]))
	if updated is None or expires is None or digest is None:
		raise DataError("expected #$ (last update), #@ (expiry), and #h (hash) lines")
	if not updated.isdigit() or not expires.isdigit():
		raise DataError("expected NTP seconds in the #$ and #@ lines")

	# The hash covers the update time, the expiry, and the numbers of each data line.
	hashed = updated + expires + "".join(ntp + offset for _, ntp, offset in rows)
	if hashlib.sha1(hashed.encode("ascii")).hexdigest() != digest.lower():
		raise DataError("the SHA-1 hash in the #h line does not match the data")

	leaps = []
	for line_number, ntp, offset in rows:
		days, remainder = divmod(int(ntp), 86_400)
		if remainder:
			raise DataError(f"line {line_number}: {ntp} is not the start of a UTC day")
		day = NTP_TO_JDN + days
		if civil_date(day).day != 1:
			raise DataError(f"line {line_number}: {civil_date(day)} is not the first day of a month")
		if leaps:
			previous_day, previous_offset = leaps[-1]
			if day <= previous_day:
				raise DataError(f"line {line_number}: {civil_date(day)} does not follow {civil_date(previous_day)}")
			if abs(int(offset) - previous_offset) != 1:
				raise DataError(f"line {line_number}: TAI - UTC changes from {previous_offset} s to {offset} s")
		elif day != JDN_1972 or int(offset) != 10:
			raise DataError(f"line {line_number}: expected 1972-01-01 with 10 s, the start of whole leap seconds")
		leaps.append((day, int(offset)))

	# The file expires at 0h UTC on a day, the first it does not cover.
	horizon = NTP_TO_JDN + int(expires) // 86_400
	expiry = civil_date(horizon)
	if horizon <= leaps[-1][0]:
		raise DataError(f"the file expires on {expiry}, before its last entry")
	last_update = civil_date(NTP_TO_JDN + int(updated) // 86_400)

	lines = header(args, "leap-seconds", data, args.source_url)
	if args.import_module:
		lines += ["import Astronomia", ""]
	lines += [
		f"/// TAI - UTC in whole seconds from the start of each UTC day listed, from {civil_date(leaps[0][0])}",
		f"/// to {civil_date(leaps[-1][0])}, as of {last_update}.",
		declaration(args, "[LeapSecondTable.LeapSecond]"),
	]
	for day, offset in leaps:
		lines.append(f"\t.init(effective: {day:_}, taiMinusUTC: {offset}), // {civil_date(day)}")
	lines += [
		"]",
		"",
		"/// The UTC day on which the source expires, the first it does not cover.",
		declaration(args, "JulianDayNumber", f"{horizon:_} // {expiry}", name=f"{args.name}Horizon"),
	]
	return "\n".join(lines) + "\n"


# MARK: - finals


def finals_field(line: str, first: int, last: int) -> str:
	"""Returns the 1-based, inclusive columns `first` to `last` of `line`, without spaces."""
	return line[first - 1 : last].replace(" ", "")


def finals_flag(line: str, column: int, name: str, line_number: int) -> bool:
	"""Returns whether the 1-based `column` of `line` flags a prediction (P) rather than an
	IERS value (I)."""
	flag = line[column - 1] if len(line) >= column else " "
	if flag not in "IP":
		raise DataError(f"line {line_number}: unknown {name} flag {flag!r}")
	return flag == "P"


def finals_pair(line: str, first: tuple[int, int], second: tuple[int, int], name: str, line_number: int) -> tuple[str, str] | None:
	"""Returns the values in two column ranges as Swift literals, or None if both are blank."""
	a = finals_field(line, *first)
	b = finals_field(line, *second)
	if not a and not b:
		return None
	if not a or not b:
		raise DataError(f"line {line_number}: {name} has only one of its two values")
	return swift_literal(a, line_number), swift_literal(b, line_number)


def ranges(flags: list[bool]) -> list[tuple[int, int]]:
	"""Returns the half-open ranges of indices where `flags` is true."""
	result = []
	start = None
	for index, flag in enumerate(flags + [False]):
		if flag and start is None:
			start = index
		elif not flag and start is not None:
			result.append((start, index))
			start = None
	return result


def finals(args: argparse.Namespace, data: bytes) -> str:
	"""Uses the fixed columns of the IERS finals2000A format and its Bulletin A values: the MJD
	of 0h UTC in columns 8-15; polar motion x_p and y_p, in arcseconds, in columns 19-27 and
	38-46, flagged as IERS (I) or predicted (P) values in column 17; UT1 - UTC in columns
	59-68, flagged in column 58; the excess length of day, in milliseconds, in columns 80-86;
	and the celestial pole offsets dX and dY, in milliarcseconds, in columns 98-106 and
	117-125, flagged in column 96. Rows without UT1 - UTC are skipped. Without predictions,
	predicted rows of UT1 - UTC are skipped and other predicted values are left out.

	With --ut1-only, only UT1 - UTC is read. Use it for IAU 1980 finals files, whose columns
	98-125 hold dψ and dε instead of dX and dY."""
	start = civil_jdn(args.start) if args.start else None
	end = civil_jdn(args.end) if args.end else None
	rows = []
	previous_day = None
	for line_number, line in enumerate(data.decode("ascii").splitlines(), start=1):
		value = finals_field(line, 59, 68)
		if not value:
			continue
		is_predicted = finals_flag(line, 58, "UT1 - UTC", line_number)
		if is_predicted and not args.predictions:
			continue

		mjd_text = line[7:15].strip()
		if not NUMBER.match(mjd_text) or Fraction(mjd_text).denominator != 1:
			raise DataError(f"line {line_number}: expected a whole MJD, found {mjd_text!r}")
		mjd = int(Fraction(mjd_text))
		day = mjd + MJD_TO_JDN
		ut1_minus_utc = swift_literal(value, line_number)
		if abs(float(ut1_minus_utc)) >= 1:
			raise DataError(f"line {line_number}: UT1 - UTC {ut1_minus_utc} is not less than a second")
		if previous_day is not None and day <= previous_day:
			raise DataError(f"line {line_number}: MJD {mjd} does not increase")
		previous_day = day

		pole = offsets = lod = None
		pole_predicted = offsets_predicted = False
		if not args.ut1_only:
			pole = finals_pair(line, (19, 27), (38, 46), "polar motion", line_number)
			if pole is not None:
				pole_predicted = finals_flag(line, 17, "polar motion", line_number)
				if pole_predicted and not args.predictions:
					pole = None
			offsets = finals_pair(line, (98, 106), (117, 125), "dX and dY", line_number)
			if offsets is not None:
				offsets_predicted = finals_flag(line, 96, "nutation", line_number)
				if offsets_predicted and not args.predictions:
					offsets = None
			lod_text = finals_field(line, 80, 86)
			lod = swift_literal(lod_text, line_number) if lod_text else None

		if (start is not None and day < start) or (end is not None and day > end):
			continue
		rows.append(
			{
				"day": day,
				"ut1": ut1_minus_utc,
				"ut1_predicted": is_predicted,
				"pole": pole,
				"pole_predicted": pole is not None and pole_predicted,
				"offsets": offsets,
				"offsets_predicted": offsets is not None and offsets_predicted,
				"lod": lod,
			}
		)
	if len(rows) < 2:
		raise DataError("expected at least two rows with UT1 - UTC in the selected dates")

	first, last = civil_date(rows[0]["day"]), civil_date(rows[-1]["day"])
	days = [row["day"] for row in rows]
	predicted = sum(row["ut1_predicted"] for row in rows)
	has_pole = any(row["pole"] for row in rows)
	has_offsets = any(row["offsets"] for row in rows)
	has_lod = any(row["lod"] for row in rows)

	lines = header(args, "finals", data, args.source_url)
	if args.import_module:
		lines += ["import Astronomia", ""]
	documentation = len(lines)
	lines.append(f"/// IERS Bulletin A Earth orientation parameters at 0h UTC from {first} to {last}.")
	lines.append("///")
	included = ["UT1 - UTC"]
	if has_pole:
		included.append("polar motion")
	if has_offsets:
		included.append("celestial pole offsets")
	if has_lod:
		included.append("excess length of day")
	text = included[0] if len(included) == 1 else ", ".join(included[:-1]) + (", and " if len(included) > 2 else " and ") + included[-1]
	lines.append(f"/// {text[0].upper() + text[1:]}.")
	if predicted:
		entries = "entry's UT1 - UTC is a prediction" if predicted == 1 else "entries' UT1 - UTC are predictions"
		lines.append(f"/// {predicted:,} {entries}, flagged by `isPredicted`.")

	def pole_initializer(row: dict) -> str:
		x, y = row["pole"]
		return f"PolarMotion(x: Angle(arcseconds: {x}), y: Angle(arcseconds: {y}), isPredicted: {swift_bool(row['pole_predicted'])})"

	def offsets_initializer(row: dict) -> str:
		dx, dy = row["offsets"]
		return f"CelestialPoleOffsets(dX: Angle(milliarcseconds: {dx}), dY: Angle(milliarcseconds: {dy}), isPredicted: {swift_bool(row['offsets_predicted'])})"

	if args.array:
		# One initializer per row: readable, but slow to compile for more than a few
		# thousand rows.
		width = max(len(row["ut1"]) for row in rows)
		lines.append(declaration(args, "[EarthOrientationTable.Entry]"))
		for row in rows:
			text = f"utcDay: {row['day']:_}, ut1MinusUTC: {(row['ut1'] + ',').ljust(width + 1)} isPredicted: {swift_bool(row['ut1_predicted'])}"
			if row["pole"]:
				text += f", polarMotion: {pole_initializer(row)}"
			if row["offsets"]:
				text += f", celestialPoleOffsets: {offsets_initializer(row)}"
			if row["lod"]:
				text += f", excessLengthOfDay: {row['lod']} / 1000"
			lines.append(f"\t.init({text}), // {civil_date(row['day'])}")
		lines.append("]")
		return "\n".join(lines) + "\n"

	# Large array literals of struct initializers are slow for the Swift compiler to type
	# check, so the values are written as [Double] literals and the entries built from them
	# on first use. The arrays are private constants at file scope, ahead of the declaration:
	# inside the closure that builds the entries, the compiler type checks them with the rest
	# of the closure's body, which is several times slower. Consecutive days, the usual case,
	# need only the first. Predictions are written as ranges of indices. Each optional column
	# runs from the first row with a value to the last, with NaN for a value missing in
	# between.
	if args.table:
		lines.append("///")
		lines.append("/// Converted to ΔT with the built-in leap seconds on first use.")
		lines.append(declaration(args, "EarthOrientationTable", "{"))
	else:
		lines.append(declaration(args, "[EarthOrientationTable.Entry]", "{"))
	consecutive = all(b - a == 1 for a, b in zip(days, days[1:]))
	if consecutive:
		lines.append(f"\tlet firstUTCDay = {days[0]:_}")

	columns: list[str] = []

	def column(name: str, type_name: str, items: list[str], per_line: int, per_row: int = 1, first_row: int = 0, comment: str | None = None) -> None:
		width = max(len(item) for item in items)
		if comment:
			columns.append(f"// {comment}")
		columns.append(f"private let {name}: [{type_name}] = [")
		for start in range(0, len(items), per_line):
			chunk = items[start : start + per_line]
			text = " ".join((item + ",").ljust(width + 1) for item in chunk).rstrip()
			columns.append(f"\t{text} // {civil_date(days[first_row + start // per_row])}")
		columns.extend(["]", ""])

	def predictions(name: str, flags: list[bool]) -> bool:
		spans = ranges(flags)
		if spans:
			items = ", ".join(f"{a:_} ..< {b:_}" for a, b in spans)
			lines.append(f"\tlet {name}: [Range<Int>] = [{items}]")
		return bool(spans)

	def values(key: str, name: str) -> tuple[list, str]:
		"""The values of `key` from the first row that has one to the last, and the expression
		for a row's offset into them, declaring the first row's index if it is not 0."""
		present = [index for index, row in enumerate(rows) if row[key]]
		first_row = present[0]
		if first_row:
			lines.append(f"\tlet {name}Start = {first_row:_}")
		return [row[key] for row in rows[first_row : present[-1] + 1]], f"index - {name}Start" if first_row else "index"

	def first_present(key: str) -> int:
		return next(index for index, row in enumerate(rows) if row[key])

	if not consecutive:
		column("utcDays", "Int", [f"{day:_}" for day in days], 8)
	column("ut1MinusUTC", "Double", [row["ut1"] for row in rows], 8, comment="UT1 - UTC, in seconds")
	ut1_ranges = predictions("ut1Predictions", [row["ut1_predicted"] for row in rows])
	if has_pole:
		pole_values, pole_index = values("pole", "polarMotion")
		items = [item for pair in pole_values for item in (pair or (".nan", ".nan"))]
		column("polarMotion", "Double", items, 8, 2, first_present("pole"), "x_p and y_p, in arcseconds")
		pole_ranges = predictions("polarMotionPredictions", [row["pole_predicted"] for row in rows])
	if has_offsets:
		offsets_values, offsets_index = values("offsets", "celestialPoleOffsets")
		items = [item for pair in offsets_values for item in (pair or (".nan", ".nan"))]
		column("celestialPoleOffsets", "Double", items, 8, 2, first_present("offsets"), "dX and dY, in milliarcseconds")
		offsets_ranges = predictions("celestialPoleOffsetPredictions", [row["offsets_predicted"] for row in rows])
	if has_lod:
		lod_values, lod_index = values("lod", "excessLengthOfDay")
		column("excessLengthOfDay", "Double", [item or ".nan" for item in lod_values], 8, 1, first_present("lod"), "Excess length of day, in milliseconds")

	if (ut1_ranges or (has_pole and pole_ranges) or (has_offsets and offsets_ranges)):
		lines += [
			"\tfunc isPredicted(_ index: Int, _ predictions: [Range<Int>]) -> Bool {",
			"\t\tpredictions.contains { $0.contains(index) }",
			"\t}",
		]

	def pair_index(index: str) -> str:
		return "2 * index" if index == "index" else f"2 * ({index})"

	def bounds(name: str, index: str) -> str:
		"""The condition that `i` is within the column `name`, which starts at row 0 when
		`index` is plain `index`."""
		return f"i < {name}.count" if index == "index" else f"i >= 0, i < {name}.count"

	def flag(ranges_present: bool, name: str) -> str:
		return f"isPredicted(index, {name})" if ranges_present else "false"

	arguments = [
		f"utcDay: {'firstUTCDay + index' if consecutive else 'utcDays[index]'}",
		"ut1MinusUTC: ut1MinusUTC[index]",
		f"isPredicted: {flag(ut1_ranges, 'ut1Predictions')}",
	]
	if has_pole:
		lines += [
			"\tfunc pole(_ index: Int) -> PolarMotion? {",
			f"\t\tlet i = {pair_index(pole_index)}",
			f"\t\tguard {bounds('polarMotion', pole_index)}, !polarMotion[i].isNaN else {{ return nil }}",
			"\t\tlet x = Angle(arcseconds: polarMotion[i])",
			"\t\tlet y = Angle(arcseconds: polarMotion[i + 1])",
			f"\t\treturn PolarMotion(x: x, y: y, isPredicted: {flag(pole_ranges, 'polarMotionPredictions')})",
			"\t}",
		]
		arguments.append("polarMotion: pole(index)")
	if has_offsets:
		lines += [
			"\tfunc offsets(_ index: Int) -> CelestialPoleOffsets? {",
			f"\t\tlet i = {pair_index(offsets_index)}",
			f"\t\tguard {bounds('celestialPoleOffsets', offsets_index)}, !celestialPoleOffsets[i].isNaN else {{ return nil }}",
			"\t\tlet dX = Angle(milliarcseconds: celestialPoleOffsets[i])",
			"\t\tlet dY = Angle(milliarcseconds: celestialPoleOffsets[i + 1])",
			f"\t\treturn CelestialPoleOffsets(dX: dX, dY: dY, isPredicted: {flag(offsets_ranges, 'celestialPoleOffsetPredictions')})",
			"\t}",
		]
		arguments.append("celestialPoleOffsets: offsets(index)")
	if has_lod:
		lines += [
			"\tfunc lengthOfDay(_ index: Int) -> Double? {",
			f"\t\tlet i = {lod_index}",
			f"\t\tguard {bounds('excessLengthOfDay', lod_index)}, !excessLengthOfDay[i].isNaN else {{ return nil }}",
			"\t\treturn excessLengthOfDay[i] / 1000",
			"\t}",
		]
		arguments.append("excessLengthOfDay: lengthOfDay(index)")

	build = ["ut1MinusUTC.indices.map { index in", "\tEarthOrientationTable.Entry("]
	build += [f"\t\t{argument}," for argument in arguments[:-1]] + [f"\t\t{arguments[-1]}"]
	build += ["\t)", "}"]
	if args.table:
		lines.append(f"\tlet entries = {build[0]}")
		lines += [f"\t{line}" for line in build[1:]]
		lines += [
			"\t// The generator checked the entries, and the built-in leap seconds cover them.",
			"\tguard let table = EarthOrientationTable(entries: entries) else {",
			"\t\tpreconditionFailure(\"Invalid Earth orientation entries\")",
			"\t}",
			"\treturn table",
		]
	else:
		lines.append(f"\treturn {build[0]}")
		lines += [f"\t{line}" for line in build[1:]]
	lines.append("}()")
	lines[documentation:documentation] = columns
	return "\n".join(lines) + "\n"


def swift_bool(value: bool) -> str:
	return "true" if value else "false"


# MARK: - Main


def main() -> None:
	parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	commands = parser.add_subparsers(dest="command", required=True)

	def add_common(command: argparse.ArgumentParser, name: str, source_url: str) -> None:
		command.add_argument("file", help="the data file to read")
		command.add_argument("--name", help=f"the Swift constant's name (default: {name})")
		command.add_argument(
			"--access",
			choices=["public", "package", "internal", "fileprivate", "private"],
			default="internal",
			help="the Swift constant's access level (default: internal)",
		)
		command.add_argument("--source-url", default=source_url, help="the source recorded in the header")
		command.add_argument("--spdx", action="store_true", help="begin with Astronomia's license header")

	historic = commands.add_parser("historic-delta-t", help="USNO historic_deltat.data", description=historic_delta_t.__doc__)
	add_common(historic, "historicDeltaTEntries", "https://maia.usno.navy.mil/ser7/historic_deltat.data")
	historic.set_defaults(generate=historic_delta_t)

	modern = commands.add_parser("modern-delta-t", help="USNO deltat.data", description=modern_delta_t.__doc__)
	add_common(modern, "modernDeltaTEntries", "https://maia.usno.navy.mil/ser7/deltat.data")
	modern.set_defaults(generate=modern_delta_t)

	leap = commands.add_parser("leap-seconds", help="IERS/IETF leap-seconds.list", description=leap_seconds.__doc__)
	add_common(leap, "builtInLeapSeconds", "https://hpiers.obspm.fr/iers/bul/bulc/ntp/leap-seconds.list")
	leap.add_argument(
		"--no-import",
		dest="import_module",
		action="store_false",
		help="leave out `import Astronomia`, for a file in the Astronomia module itself",
	)
	leap.set_defaults(generate=leap_seconds)

	finals_command = commands.add_parser("finals", help="IERS finals2000A", description=finals.__doc__)
	add_common(finals_command, "finalsEntries, or earthOrientationTable with --table", "https://maia.usno.navy.mil/ser7/finals2000A.all")
	finals_command.add_argument(
		"--no-import",
		dest="import_module",
		action="store_false",
		help="leave out `import Astronomia`, for a file in the Astronomia module itself",
	)
	form = finals_command.add_mutually_exclusive_group()
	form.add_argument(
		"--table",
		action="store_true",
		help="write an EarthOrientationTable built with the built-in leap seconds instead of an array of entries",
	)
	form.add_argument(
		"--array",
		action="store_true",
		help="write the entries as an array literal of initializers, one per row; readable, but slow to compile for large files",
	)
	finals_command.add_argument("--start", type=datetime.date.fromisoformat, help="the first UTC day to include, YYYY-MM-DD")
	finals_command.add_argument("--end", type=datetime.date.fromisoformat, help="the last UTC day to include, YYYY-MM-DD")
	finals_command.add_argument(
		"--no-predictions", dest="predictions", action="store_false", help="leave out values flagged as predictions"
	)
	finals_command.add_argument(
		"--ut1-only",
		action="store_true",
		help="read only UT1 - UTC, as for IAU 1980 finals files, or for a smaller table",
	)
	finals_command.set_defaults(generate=finals)

	args = parser.parse_args()
	if args.name is None:
		if args.command == "historic-delta-t":
			args.name = "historicDeltaTEntries"
		elif args.command == "modern-delta-t":
			args.name = "modernDeltaTEntries"
		elif args.command == "leap-seconds":
			args.name = "builtInLeapSeconds"
		else:
			args.name = "earthOrientationTable" if args.table else "finalsEntries"
	with open(args.file, "rb") as file:
		data = file.read()
	try:
		sys.stdout.write(args.generate(args, data))
	except DataError as error:
		sys.exit(f"{os.path.basename(args.file)}: {error}")


if __name__ == "__main__":
	main()
