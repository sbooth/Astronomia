"""Writes IAU 2006/2000A reference values from ERFA as a Swift test fixture.

The values cover J1000.0 to J3000.0 and dates near the present: nutation, the precession
angles, the precession-nutation matrix, X, Y and s, the equations of the equinoxes and the
origins, Greenwich apparent sidereal time, the matrices of the frames of date, the CIRS with
celestial pole offsets, and the terrestrial frames with polar motion.

Requires:
  pyerfa 2.0.1.5 (ERFA 2.0.1)

Usage:
  Scripts/Fixtures/erfa-iau2006.py Tests/AstronomiaTests/EarthOrientation/ERFAIAU2006.swift
"""

import erfa, sys
if len(sys.argv) != 2:
	sys.exit("usage: Scripts/Fixtures/erfa-iau2006.py OUTPUT")

J2000 = 2451545.0
# TT Julian Dates: J1000.0 to J3000.0 every 100 years, plus dates near the present
dates = [J2000 + 365.25 * years for years in range(-1000, 1001, 100)]
dates += [2433282.5, 2451545.0, 2455197.5, 2460000.5, 2460967.25, 2469807.5]
dates = sorted(set(dates))
rows = []
for jd in dates:
	d1, d2 = jd, 0.0
	dpsi, deps = (float(v) for v in erfa.nut06a(d1, d2))
	gamb, phib, psib, epsa = (float(v) for v in erfa.pfw06(d1, d2))
	rnpb = erfa.pnm06a(d1, d2)
	x, y = (float(v) for v in erfa.bpn2xy(rnpb))
	s = float(erfa.s06(d1, d2, x, y))
	eect = float(erfa.eect00(d1, d2))
	ee = float(erfa.ee06a(d1, d2))
	# UT1 = TT, so the ERA and the precession share the date
	gst = float(erfa.gst06a(d1, d2, d1, d2))
	eo = float(erfa.eo06a(d1, d2))
	m = ", ".join(repr(float(v)) for v in rnpb.flatten())
	def flat(r):
		return "[" + ", ".join(repr(float(v)) for v in r.flatten()) + "]"
	rb, rp, rbp = erfa.bp06(d1, d2)
	ecm = erfa.ecm06(d1, d2)
	c2i = erfa.c2i06a(d1, d2)
	true_ecliptic = erfa.rx(epsa + deps, rnpb)
	frames = f"[{flat(rbp)}, {flat(ecm)}, {flat(c2i)}, {flat(true_ecliptic)}]"
	rows.append(f"\t({jd!r}, [{dpsi!r}, {deps!r}], [{gamb!r}, {phib!r}, {psib!r}, {epsa!r}], [{m}], [{x!r}, {y!r}, {s!r}], [{eect!r}, {ee!r}, {gst!r}, {eo!r}], {frames}),")
out = [
	"//",
	"// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>",
	"// SPDX-License-Identifier: MIT",
	"//",
	"// Part of https://github.com/sbooth/Astronomia",
	"//",
	"",
	"// Generated by Scripts/Fixtures/erfa-iau2006.py. Do not edit.",
	"",
	f"/// IAU 2006/2000A reference values from ERFA {erfa.version.erfa_version} (pyerfa {erfa.__version__}), in",
	"/// radians, at TT Julian Dates: nut06a (Δψ, Δε), pfw06 (γ̄, φ̄, ψ̄, ε_A), pnm06a (the matrix by",
	"/// rows), bpn2xy and s06 (X, Y, s), eect00, ee06a, gst06a with UT1 = TT, and eo06a, and the",
	"/// matrices, by rows, of the frames of date: bp06 (the mean equator), ecm06 (the mean",
	"/// ecliptic), c2i06a (the CIRS), and R1(ε_A + Δε) times pnm06a (the true ecliptic).",
	"let erfaIAU2006: [(julianDate: Double, nutation: [Double], angles: [Double], matrix: [Double], cip: [Double], siderealTime: [Double], frames: [[Double]])] = [",
] + rows + ["]", ""]
# The CIRS with celestial pole offsets of 0.3 mas in X and -0.2 mas in Y
dx, dy = 0.3e-3 * erfa.DAS2R, -0.2e-3 * erfa.DAS2R
offsets = []
for jd in (2451545.0, 2460000.5, 2469807.5):
	x, y = erfa.bpn2xy(erfa.pnm06a(jd, 0.0))
	s = erfa.s06(jd, 0.0, x, y)
	c2i = erfa.c2ixys(x + dx, y + dy, s)
	offsets.append(f"\t({jd!r}, [" + ", ".join(repr(float(v)) for v in c2i.flatten()) + "]),")
out += [
	"/// The CIRS by c2ixys with celestial pole offsets dX = 0.3 mas and dY = -0.2 mas added to X",
	"/// and Y from pnm06a, with s from s06 for the model's X and Y.",
	"let erfaCIRSWithPoleOffsets: [(julianDate: Double, matrix: [Double])] = [",
] + offsets + ["]", ""]
# The terrestrial frames with UT1 = TT - 69.184 s and polar motion of 0.12" and 0.34"
xp, yp = 0.12 * erfa.DAS2R, 0.34 * erfa.DAS2R
terrestrial = []
for jd in (2451545.0, 2460000.5, 2460967.25):
	# UT1 in two parts, which ERFA keeps exactly
	ut1 = -69.184 / 86400
	c2t = erfa.c2t06a(jd, 0.0, jd, ut1, xp, yp)
	era = float(erfa.era00(jd, ut1))
	tirs = erfa.rz(era, erfa.c2i06a(jd, 0.0))
	pom = erfa.pom00(xp, yp, erfa.sp00(jd, 0.0))
	flat = lambda r: "[" + ", ".join(repr(float(v)) for v in r.flatten()) + "]"
	terrestrial.append(f"\t({jd!r}, {flat(c2t)}, {flat(tirs)}, {flat(pom)}),")
out += [
	"/// The terrestrial frames with UT1 = TT - 69.184 s and polar motion x_p = 0.12\" and",
	"/// y_p = 0.34\": c2t06a (the ITRS), era00 times c2i06a (the TIRS), and pom00, by rows.",
	"let erfaTerrestrial: [(julianDate: Double, itrs: [Double], tirs: [Double], polarMotion: [Double])] = [",
] + terrestrial + ["]", ""]
open(sys.argv[1], "w").write("\n".join(out))
