"""Writes geocentric places of solar system bodies from Skyfield and DE421 as a Swift fixture.

For each body and date: the astrometric position with its light time, and the apparent
position, with deflection by the Sun, Jupiter and Saturn and aberration.

Requires:
  Skyfield 1.55
  DE421: de421.bsp, from https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/de421.bsp

Usage:
  Scripts/Fixtures/skyfield-places.py de421.bsp \\
      Tests/AstronomiaTests/Astrometry/SkyfieldPlaces.swift
"""

import sys
from skyfield.api import load_file, load
import skyfield
if len(sys.argv) != 3:
	sys.exit("usage: Scripts/Fixtures/skyfield-places.py DE421 OUTPUT")

eph = load_file(sys.argv[1])
ts = load.timescale(builtin=True)
earth = eph["earth"]
bodies = [("sun", "sun"), ("moon", "moon"), ("mercury", "mercury"), ("venus", "venus"), ("mars", "mars"),
	("jupiterBarycenter", "jupiter barycenter"), ("saturnBarycenter", "saturn barycenter"),
	("uranusBarycenter", "uranus barycenter"), ("neptuneBarycenter", "neptune barycenter"), ("plutoBarycenter", "pluto barycenter")]
dates = [2433282.5, 2440000.5, 2447892.5, 2451545.0, 2455000.5, 2458849.5, 2460000.5, 2460967.25, 2465000.5, 2469807.5]
rows = []
for jd in dates:
	t = ts.tdb_jd(jd)
	for name, key in bodies:
		astrometric = earth.at(t).observe(eph[key])
		apparent = astrometric.apparent()
		a = astrometric.position.au
		p = apparent.position.au
		rows.append(f"\t({jd!r}, .{name}, [{float(a[0])!r}, {float(a[1])!r}, {float(a[2])!r}], {float(astrometric.light_time)!r}, [{float(p[0])!r}, {float(p[1])!r}, {float(p[2])!r}]),")
out = [
	"//",
	"// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>",
	"// SPDX-License-Identifier: MIT",
	"//",
	"// Part of https://github.com/sbooth/Astronomia",
	"//",
	"",
	"// Generated by Scripts/Fixtures/skyfield-places.py. Do not edit.",
	"",
	"@testable import Astronomia",
	"",
	f"/// Geocentric places from Skyfield {skyfield.__version__} and DE421 at TDB Julian Dates: the astrometric",
	"/// position, in au in the ICRS, its light time, in days, and the apparent position, with",
	"/// deflection by the Sun, Jupiter, and Saturn and aberration.",
	"let skyfieldPlaces: [(julianDate: Double, body: BuiltInEphemeris.Body, astrometric: [Double], lightTime: Double, apparent: [Double])] = [",
] + rows + ["]", ""]
open(sys.argv[2], "w").write("\n".join(out))
