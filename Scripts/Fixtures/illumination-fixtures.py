"""Writes the illumination of the Moon and the planets from Skyfield as a Swift test fixture.

For each body and instant, seen from the geocenter or from a wgs84 site with UT1 = TT - 69.2 s:

  The phase angle, the angle at the body between the Sun and the observer, from Skyfield's
  phase_angle of the astrometric position, and the illuminated fraction, (1 + cos i) / 2.

  The elongation, the separation of the apparent places of the body and the Sun.

  The position angle of the bright limb, the Sun's position angle from the body, from
  position_angle_of with their apparent right ascensions and declinations of date.

Requires:
  Skyfield 1.55, NumPy
  DE421: de421.bsp, from https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/de421.bsp

Usage:
  Scripts/Fixtures/illumination-fixtures.py de421.bsp \\
      Tests/AstronomiaTests/Astrometry/IlluminationFixtures.swift

The large tables are written as text fixtures in Tests/AstronomiaTests/Fixtures, which the
Swift fixture reads when first used; see text_fixture.py.
"""

import sys
import text_fixture
import skyfield
from skyfield.api import load, load_file, wgs84
from skyfield.trigonometry import position_angle_of
if len(sys.argv) != 3:
	sys.exit("usage: Scripts/Fixtures/illumination-fixtures.py DE421 OUTPUT")

eph = load_file(sys.argv[1])
ts = load.timescale(builtin=True, delta_t=69.2)
sun = eph["sun"]
earth = eph["earth"]

# Swift body, Skyfield body
bodies = [
	(".moon", "moon"),
	(".mercury", "mercury"),
	(".venus", "venus"),
	(".mars", "mars"),
	(".jupiterBarycenter", "jupiter barycenter"),
	(".saturnBarycenter", "saturn barycenter"),
]
# Swift site index (-1 for the geocenter), latitude (deg), longitude (deg), height (m)
sites = [
	(-1, None, None, None),
	(0, 51.4769, -0.0005, 46.0),
	(1, 19.8207, -155.4681, 4205.0),
]

def row(body, site, tt):
	t = ts.tt_jd(tt)
	name = dict(bodies)[body]
	observer = earth if site[0] < 0 else earth + wgs84.latlon(site[1], site[2], elevation_m=site[3])
	at = observer.at(t)
	astrometric = at.observe(eph[name])
	phase = astrometric.phase_angle(sun)
	fraction = astrometric.fraction_illuminated(sun)
	target = astrometric.apparent()
	light = at.observe(sun).apparent()
	elongation = target.separation_from(light)
	ra, dec, _ = target.radec(epoch="date")
	sra, sdec, _ = light.radec(epoch="date")
	limb = position_angle_of((dec, ra), (sdec, sra))
	return (body[1:], site[0], tt, float(phase.degrees), float(fraction), float(elongation.degrees), float(limb.degrees))

rows = []
# The Moon from the geocenter through two synodic months, every 1.5 days, and every 97 days
# from 2000 to 2049
for k in range(40):
	rows.append(row(".moon", sites[0], 2461041.5 + 1.5 * k))
for k in range(190):
	rows.append(row(".moon", sites[0], 2451545.25 + 97.0 * k))
# The Moon from the sites through a synodic month
for site in sites[1:]:
	for k in range(20):
		rows.append(row(".moon", site, 2461041.5 + 1.5 * k + 0.13 * site[0]))
# The planets from the geocenter every 61 days for three years, and from a site
for body, _ in bodies[1:]:
	for k in range(18):
		rows.append(row(body, sites[0], 2460676.5 + 61.0 * k))
	rows.append(row(body, sites[2], 2461100.5))

out = [
	"//", "// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>", "// SPDX-License-Identifier: MIT", "//",
	"// Part of https://github.com/sbooth/Astronomia", "//", "",
	"// Generated by Scripts/Fixtures/illumination-fixtures.py. Do not edit.", "",
	"@testable import Astronomia", "",
	f"/// The illumination of the Moon and the planets from Skyfield {skyfield.__version__} with DE421: the body, the",
	"/// site's index in the sites of `IlluminationTests`, -1 for the geocenter, the TT Julian Date, and",
	"/// the phase angle, the illuminated fraction, the elongation, and the position angle of the",
	"/// bright limb, in degrees but for the fraction.",
	"let skyfieldIllumination: [(body: BuiltInEphemeris.Body, site: Int, julianDate: Double, phaseAngle: Double, fraction: Double, elongation: Double, brightLimb: Double)] = textFixture(\"SkyfieldIllumination\") { row in",
	"\t(row.value(), row.int(), row.double(), row.double(), row.double(), row.double(), row.double())",
	"}", "",
]
open(sys.argv[2], "w").write("\n".join(out))
text_fixture.write(sys.argv[2], "skyfieldIllumination", "Scripts/Fixtures/illumination-fixtures.py", "body site julianDate phaseAngle fraction elongation brightLimb", rows)
