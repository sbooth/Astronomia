"""Writes an excerpt of DE421 and the states of its segments from jplephem as test fixtures.

The excerpt, De421Excerpt.bsp in Tests/AstronomiaTests/Fixtures, is January 2026 of each of
DE421's segments, cut by jplephem's excerpt command, about 17 KB. The states are each
segment's, in kilometers and kilometers per second, at instants across its interval: its
first and last instants, the boundaries between some of its records, and instants between.

Requires:
  jplephem 2.24
  DE421: de421.bsp, from https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/de421.bsp

Usage:
  Scripts/Fixtures/spk-fixtures.py de421.bsp Tests/AstronomiaTests/Ephemerides/SPKFixtures.swift

The states are written as a text fixture in Tests/AstronomiaTests/Fixtures, which the Swift
fixture reads when first used; see text_fixture.py.
"""

import os, subprocess, sys
import text_fixture
import jplephem
from jplephem.spk import SPK
if len(sys.argv) != 3:
	sys.exit("usage: Scripts/Fixtures/spk-fixtures.py DE421 OUTPUT")

S_PER_DAY = 86400.0
J2000 = 2451545.0
fixtures = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(sys.argv[2]))), "Fixtures")
excerpt = os.path.join(fixtures, "De421Excerpt.bsp")
subprocess.run([sys.executable, "-m", "jplephem", "excerpt", "2026/1/1", "2026/2/1", sys.argv[1], excerpt], check=True, stdout=subprocess.DEVNULL)

kernel = SPK.open(excerpt)
rows = []
for segment in kernel.segments:
	# load_array gives the first instant and the length of the records in days
	init, intlen, coefficients = segment.load_array()
	init, intlen = (init - J2000) * S_PER_DAY, intlen * S_PER_DAY
	start, end = segment.start_second, segment.end_second
	instants = [start, end]
	instants += [start + fraction * (end - start) for fraction in (0.1234567, 0.5, 0.8765432)]
	# The first boundaries between records within the segment
	instants += [init + k * intlen for k in range(1, 3) if init + k * intlen < end]
	for seconds in sorted(set(instants)):
		position, velocity = segment.compute_and_differentiate(J2000, seconds / S_PER_DAY)
		rows.append((segment.target, segment.center, seconds, [float(v) for v in position], [float(v) / S_PER_DAY for v in velocity]))
kernel.close()

out = [
	"//",
	"// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>",
	"// SPDX-License-Identifier: MIT",
	"//",
	"// Part of https://github.com/sbooth/Astronomia",
	"//",
	"",
	"// Generated by Scripts/Fixtures/spk-fixtures.py. Do not edit.",
	"",
	f"/// States of the segments of Fixtures/De421Excerpt.bsp, January 2026 of DE421, from jplephem",
	f"/// {jplephem.__version__}: the target, the center, TDB seconds from J2000.0, the position, in km, and the",
	"/// velocity, in km/s.",
	"let jplephemSPKStates: [(target: Int, center: Int, seconds: Double, position: [Double], velocity: [Double])] = textFixture(\"JplephemSPKStates\") { row in",
	"\t(row.int(), row.int(), row.double(), row.vector(), row.vector())",
	"}",
	"",
]
open(sys.argv[2], "w").write("\n".join(out))
text_fixture.write(sys.argv[2], "jplephemSPKStates", "Scripts/Fixtures/spk-fixtures.py", "target center seconds position.x position.y position.z velocity.x velocity.y velocity.z", rows)
