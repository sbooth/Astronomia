"""Writes text fixtures: the large tables of the tests, which they read when first used.

The compiler takes minutes and gigabytes to type-check large tables as Swift literals, so a
generated Swift fixture declares each large table as a call to `textFixture`, and the rows are a
text file in Tests/AstronomiaTests/Fixtures, one row per line, its fields separated by spaces.
A number is written with repr, so it reads back as the same Double; an enumeration's case by
its name, as `newMoon`; `None` as `nil`; and a vector or a list as its elements in turn.
"""

import os
from numbers import Integral, Real

HEADER = [
	"# SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>",
	"# SPDX-License-Identifier: MIT",
	"#",
	"# Part of https://github.com/sbooth/Astronomia",
	"#",
]


def fields(value):
	"""Returns the text of the fields of a value."""
	if value is None:
		return ["nil"]
	if isinstance(value, bool):
		return ["true" if value else "false"]
	if isinstance(value, str):
		return [value]
	if isinstance(value, Integral):
		return [str(int(value))]
	if isinstance(value, Real):
		return [repr(float(value))]
	return [field for element in value for field in fields(element)]


def write(swift_path, name, script, columns, rows):
	"""Writes the rows of the table `name`, declared in the Swift fixture at swift_path.

	The file is Fixtures/<Name>.txt in the test target, beside the directory of the Swift
	fixture, with a header naming the script, the table, and its columns.

	Args:
	  swift_path: The path of the Swift fixture, in a directory of the test target.
	  name: The name of the Swift table, as skyfieldMoonPhases.
	  script: The script generating it, as Scripts/Fixtures/moon-phase-fixtures.py.
	  columns: The names of the columns.
	  rows: The rows, each a sequence of values.
	"""
	directory = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(swift_path))), "Fixtures")
	os.makedirs(directory, exist_ok=True)
	lines = HEADER + [
		f"# Generated by {script}. Do not edit.",
		f"# The rows of `{name}` in {os.path.basename(swift_path)}, which describes them:",
		"# " + columns,
	] + [" ".join(fields(row)) for row in rows]
	# Line feeds on every platform, not the platform's newline
	with open(os.path.join(directory, name[0].upper() + name[1:] + ".txt"), "w", newline="\n") as file:
		file.write("\n".join(lines) + "\n")
