"""Writes the Moon's greatest northern and southern declinations from Skyfield as a Swift test
fixture.

The greatest declinations are the maxima and minima of the Moon's apparent geocentric
declination, in the true equator and equinox of date, from 2000 to 2049, found by Skyfield's
find_maxima to about a millisecond.

Requires:
  Skyfield 1.55, NumPy
  DE421: de421.bsp, from https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/de421.bsp

Usage:
  Scripts/Fixtures/lunar-greatest-declination-fixtures.py de421.bsp \\
      Tests/AstronomiaTests/Phenomena/LunarGreatestDeclinationFixtures.swift
"""

import sys
import skyfield
from skyfield.api import load, load_file
from skyfield.searchlib import find_maxima, find_minima

if len(sys.argv) != 3:
	sys.exit("usage: Scripts/Fixtures/lunar-greatest-declination-fixtures.py DE421 OUTPUT")

eph = load_file(sys.argv[1])
earth, moon = eph["earth"], eph["moon"]
ts = load.timescale(builtin=True)


def declination(t):
	return earth.at(t).observe(moon).apparent().radec(epoch="date")[1].radians


def negated(t):
	return -declination(t)


declination.step_days = 1
negated.step_days = 1
# A year at a time, which keeps the arrays of the search small
events = []
for year in range(2000, 2050):
	start, end = ts.tt(year, 1, 1), ts.tt(year + 1, 1, 1)
	for function, kind in ((declination, ".north"), (negated, ".south")):
		t, values = find_maxima(start, end, function, epsilon=0.001 / 86400, num=12)
		sign = 1 if kind == ".north" else -1
		events += [(float(w), float(f), kind, sign * float(v)) for w, f, v in zip(t.whole, t.tt_fraction, values)]
events.sort(key=lambda event: event[0] + event[1])
# find_maxima returns a cluster of times milliseconds apart around a flat extreme, so each
# cluster, those within a day, becomes one event, at the time of its most extreme value.
clusters = []
for event in events:
	if clusters and clusters[-1][-1][2] == event[2] and (event[0] + event[1]) - (clusters[-1][-1][0] + clusters[-1][-1][1]) < 1:
		clusters[-1].append(event)
	else:
		clusters.append([event])
events = [max(cluster, key=lambda event: abs(event[3])) for cluster in clusters]
# The declination is given by its size, which the kind signs: a negative literal is an operator
# applied to it, which makes an array of them slow to type-check.
rows = [f"\t({whole!r}, {fraction!r}, {kind}, {abs(value)!r})," for whole, fraction, kind, value in events]

out = [
	"//", "// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>", "// SPDX-License-Identifier: MIT", "//",
	"// Part of https://github.com/sbooth/Astronomia", "//", "",
	"// Generated by Scripts/Fixtures/lunar-greatest-declination-fixtures.py. Do not edit.", "",
	"@testable import Astronomia", "",
	f"/// The Moon's greatest declinations from 2000 to 2049 from Skyfield {skyfield.__version__} with DE421: the TT",
	"/// Julian Date, as a whole and a fraction, the kind, and the size of the apparent declination, in",
	"/// radians, north or south by the kind.",
	"let skyfieldLunarGreatestDeclinations: [(whole: Double, fraction: Double, kind: LunarGreatestDeclinationEvent.Kind, size: Double)] = [",
] + rows + ["]", ""]
open(sys.argv[2], "w").write("\n".join(out))
