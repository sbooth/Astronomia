"""Writes the Moon's perigees and apogees from Skyfield as a Swift test fixture.

The perigees and apogees are the minima and maxima of the Moon's geometric geocentric distance,
from the center of the Earth to the center of the Moon without light time, from 2000 to 2049,
found by Skyfield's find_maxima to about a millisecond.

Requires:
  Skyfield 1.55, NumPy
  DE421: de421.bsp, from https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/de421.bsp

Usage:
  Scripts/Fixtures/lunar-apsis-fixtures.py de421.bsp \\
      Tests/AstronomiaTests/Phenomena/LunarApsisFixtures.swift
"""

import sys
import skyfield
from skyfield.api import load, load_file
from skyfield.searchlib import find_maxima

if len(sys.argv) != 3:
	sys.exit("usage: Scripts/Fixtures/lunar-apsis-fixtures.py DE421 OUTPUT")

eph = load_file(sys.argv[1])
moon = eph["moon"] - eph["earth"]
ts = load.timescale(builtin=True)


def distance(t):
	return moon.at(t).distance().km


def negated(t):
	return -distance(t)


distance.step_days = 1
negated.step_days = 1
# A year at a time, which keeps the arrays of the search small
events = []
for year in range(2000, 2050):
	start, end = ts.tt(year, 1, 1), ts.tt(year + 1, 1, 1)
	for function, kind in ((negated, ".perigee"), (distance, ".apogee")):
		t, values = find_maxima(start, end, function, epsilon=0.001 / 86400, num=12)
		events += [(float(w), float(f), kind, abs(float(v))) for w, f, v in zip(t.whole, t.tt_fraction, values)]
# find_maxima can report, near the end of a year's search, a time that isn't its value's: keep
# only the times at which the distance is the value reported.
events = [event for event in events if abs(distance(ts.tt_jd(event[0], event[1])) - event[3]) < 1e-6]
events.sort(key=lambda event: event[0] + event[1])
# find_maxima returns a cluster of times milliseconds apart around a flat extreme, so each
# cluster, those within a day, becomes one event, at the time of its most extreme value.
clusters = []
for event in events:
	if clusters and clusters[-1][-1][2] == event[2] and (event[0] + event[1]) - (clusters[-1][-1][0] + clusters[-1][-1][1]) < 1:
		clusters[-1].append(event)
	else:
		clusters.append([event])
events = [(min if cluster[0][2] == ".perigee" else max)(cluster, key=lambda event: event[3]) for cluster in clusters]
# The rows are text, parsed when first used: a literal array of so many tuples is slow and
# memory-hungry to type-check, and repr round-trips each value exactly.
rows = [f"{whole!r} {fraction!r} {kind[1:]} {value!r}" for whole, fraction, kind, value in events]

out = [
	"//", "// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>", "// SPDX-License-Identifier: MIT", "//",
	"// Part of https://github.com/sbooth/Astronomia", "//", "",
	"// Generated by Scripts/Fixtures/lunar-apsis-fixtures.py. Do not edit.", "",
	"@testable import Astronomia", "",
	f"/// The Moon's perigees and apogees from 2000 to 2049 from Skyfield {skyfield.__version__} with DE421: the TT Julian",
	"/// Date, as a whole and a fraction, the kind, and the geometric geocentric distance, in km.",
	"let skyfieldLunarApsides: [(whole: Double, fraction: Double, kind: Moon.ApsisEvent.Kind, distance: Double)] = skyfieldLunarApsisRows",
	"\t.split(separator: \"\\n\")",
	"\t.map { row in",
	"\t\tlet fields = row.split(separator: \" \")",
	"\t\treturn (Double(fields[0])!, Double(fields[1])!, fields[2] == \"perigee\" ? .perigee : .apogee, Double(fields[3])!)",
	"\t}",
	"",
	"/// The rows of `skyfieldLunarApsides`, as text, which is quick to compile.",
	"private let skyfieldLunarApsisRows = \"\"\"",
] + rows + ['"""', ""]
open(sys.argv[2], "w").write("\n".join(out))
