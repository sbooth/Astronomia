"""Writes rises, sets, and transits from Skyfield's almanac as a Swift test fixture.

The fixture holds the events of the Sun, the Moon, Mars, Jupiter, and two stars seen from five
sites, from a low latitude to beyond the Arctic and Antarctic circles, over a few days at an
equinox and both solstices. ΔT is 69.2 s. Skyfield's horizons are: the Sun's center at -50'
(34' of refraction and a 16' radius), the Moon's center at -34' less its radius over its
distance, and -34' for the others; the Sun is also found at -6°, -12°, and -18°.

Requires:
  Skyfield 1.55, NumPy
  DE421: de421.bsp, from https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/de421.bsp

Usage:
  Scripts/Fixtures/rise-transit-set-fixtures.py de421.bsp \\
      Tests/AstronomiaTests/Astrometry/RiseTransitSetFixtures.swift

The large tables are written as text fixtures in Tests/AstronomiaTests/Fixtures, which the
Swift fixture reads when first used; see text_fixture.py.
"""

import sys
import text_fixture
import skyfield
from skyfield import almanac
from skyfield.api import Star, load, load_file, wgs84
if len(sys.argv) != 3:
	sys.exit("usage: Scripts/Fixtures/rise-transit-set-fixtures.py DE421 OUTPUT")

eph = load_file(sys.argv[1])
DELTA_T = 69.2
ts = load.timescale(builtin=True, delta_t=DELTA_T)

# name, latitude (deg), longitude (deg), height (m)
sites = [
	("greenwich", 51.4769, -0.0005, 46.0),
	("quito", -0.2, -78.5, 2850.0),
	("tromso", 69.6496, 18.956, 100.0),
	("mcmurdo", -77.846, 166.676, 10.0),
	("maunaKea", 19.8207, -155.4681, 4205.0),
]

# Stars: name, RA (deg), Dec (deg), proper motions (mas/yr), parallax (mas), RV (km/s), epoch
stars = [
	("sirius", 101.28715533, -16.71611586, -546.01, -1223.07, 379.21, -5.5, 1991.25),
	("capella", 79.17232794, 45.99799147, 75.52, -427.13, 77.29, 29.19, 1991.25),
]

# Targets: the fields of the target, a body of the built-in ephemeris or a star's index, the
# Skyfield target, the horizon (degrees, or None for Skyfield's default), and the altitude of
# the center that matches it, in arcminutes, or None for the standard upper limb
targets = [
	("body sun", eph["sun"], None, -50.0),
	("body moon", eph["moon"], None, None),
	("body mars", eph["mars"], None, -34.0),
	("body jupiterBarycenter", eph["jupiter barycenter"], None, -34.0),
	("body sun", eph["sun"], -6.0, -360.0),
	("body sun", eph["sun"], -12.0, -720.0),
	("body sun", eph["sun"], -18.0, -1080.0),
]
for index, (_, ra, dec, pmra, pmdec, px, rv, epoch) in enumerate(stars):
	star = Star(ra_hours=ra / 15, dec_degrees=dec, ra_mas_per_year=pmra, dec_mas_per_year=pmdec, parallax_mas=px, radial_km_per_s=rv, epoch=ts.J(epoch))
	targets.append((f"star {index}", star, None, -34.0))

# TT Julian Dates of the start of each interval, which is three days long
starts = [2461119.5, 2461211.5, 2461395.5]

rows = []
for site_index, (_, lat, lon, h) in enumerate(sites):
	topos = wgs84.latlon(lat, lon, elevation_m=h)
	observer = eph["earth"] + topos
	for start in starts:
		t0, t1 = ts.tt_jd(start), ts.tt_jd(start + 3)
		for name, target, horizon, altitude in targets:
			events = []
			for kind, function in (("rise", almanac.find_risings), ("set", almanac.find_settings)):
				t, crossed = function(observer, target, t0, t1, horizon_degrees=horizon)
				events += [(float(tt), kind) for tt, real in zip(t.tt, crossed) if real]
			if horizon is None:
				t = almanac.find_transits(observer, target, t0, t1)
				events += [(float(tt), "upperTransit") for tt in t.tt]
			events.sort()
			rows.append((site_index, start, name, altitude, horizon is None, events))

names = "\n".join(f"\t(\"{n}\", {lat!r}, {lon!r}, {h!r})," for n, lat, lon, h in sites)
star_rows = "\n".join(f"\t(\"{n}\", {ra!r}, {dec!r}, {pmra!r}, {pmdec!r}, {px!r}, {rv!r}, {epoch!r})," for n, ra, dec, pmra, pmdec, px, rv, epoch in stars)
out = [
	"//", "// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>", "// SPDX-License-Identifier: MIT", "//",
	"// Part of https://github.com/sbooth/Astronomia", "//", "",
	"// Generated by Scripts/Fixtures/rise-transit-set-fixtures.py. Do not edit.", "",
	"@testable import Astronomia", "",
	"/// A target of the fixtures: a body of the built-in ephemeris or one of `riseTransitSetStars`.",
	"enum RiseTransitSetTarget {",
	"\tcase body(BuiltInEphemeris.Body)",
	"\tcase star(Int)",
	"}", "",
	"/// Sites for the fixtures: the geodetic latitude and longitude, in degrees, and the height, in",
	"/// meters, on WGS84.",
	"let riseTransitSetSites: [(name: String, latitude: Double, longitude: Double, height: Double)] = [",
	names, "]", "",
	"/// Stars for the fixtures: right ascension and declination, in degrees, proper motions, in mas",
	"/// per year, parallax, in mas, radial velocity, in km/s, and Julian epoch.",
	"let riseTransitSetStars: [(name: String, rightAscension: Double, declination: Double, properMotionInRightAscension: Double, properMotionInDeclination: Double, parallax: Double, radialVelocity: Double, epoch: Double)] = [",
	star_rows, "]", "",
	f"/// Events from Skyfield {skyfield.__version__}'s almanac with DE421 and ΔT = {DELTA_T} s, over three days from a TT",
	"/// Julian Date: the site, the start, the target, the altitude of its center that matches",
	"/// Skyfield's horizon, in arcminutes, or `nil` for the standard upper limb, whether transits",
	"/// were found, and each event's TT Julian Date and kind.",
	"let skyfieldRiseTransitSetEvents: [(site: Int, start: Double, target: RiseTransitSetTarget, centerAltitude: Double?, hasTransits: Bool, events: [(julianDate: Double, kind: RiseTransitSetEvent.Kind)])] = textFixture(\"SkyfieldRiseTransitSetEvents\") { row in",
	"\tlet site = row.int()",
	"\tlet start = row.double()",
	"\tlet target: RiseTransitSetTarget = row.field() == \"star\" ? .star(row.int()) : .body(row.value())",
	"\tlet centerAltitude = row.optionalDouble()",
	"\tlet hasTransits = row.bool()",
	"\tvar events: [(julianDate: Double, kind: RiseTransitSetEvent.Kind)] = []",
	"\twhile !row.isAtEnd {",
	"\t\tevents.append((row.double(), row.value()))",
	"\t}",
	"\treturn (site, start, target, centerAltitude, hasTransits, events)",
	"}", "",
]
open(sys.argv[2], "w").write("\n".join(out))
text_fixture.write(sys.argv[2], "skyfieldRiseTransitSetEvents", "Scripts/Fixtures/rise-transit-set-fixtures.py", "site start target(body NAME or star INDEX) centerAltitude hasTransits events(julianDate kind)...", rows)
