"""Writes the Moon's passages through its ascending and descending nodes from Skyfield as a
Swift test fixture.

The passages are the instants when the Moon's apparent geocentric ecliptic latitude, in the true
ecliptic and equinox of date, crosses zero, northward at the ascending node and southward at the
descending, from 2000 to 2049, found by Skyfield's find_discrete to about a millisecond, with the
Moon's apparent ecliptic longitude there.

Requires:
  Skyfield 1.55, NumPy
  DE421: de421.bsp, from https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/de421.bsp

Usage:
  Scripts/Fixtures/lunar-node-fixtures.py de421.bsp \\
      Tests/AstronomiaTests/Phenomena/LunarNodeFixtures.swift

The large tables are written as text fixtures in Tests/AstronomiaTests/Fixtures, which the
Swift fixture reads when first used; see text_fixture.py.
"""

import sys
import text_fixture
import skyfield
from skyfield.api import load, load_file
from skyfield.framelib import ecliptic_frame
from skyfield.searchlib import find_discrete

if len(sys.argv) != 3:
	sys.exit("usage: Scripts/Fixtures/lunar-node-fixtures.py DE421 OUTPUT")

eph = load_file(sys.argv[1])
earth, moon = eph["earth"], eph["moon"]
ts = load.timescale(builtin=True)


def place(t):
	latitude, longitude, _ = earth.at(t).observe(moon).apparent().frame_latlon(ecliptic_frame)
	return latitude.radians, longitude.radians


def north(t):
	return place(t)[0] >= 0


north.step_days = 1
# A year at a time, which keeps the arrays of the search small
events = []
for year in range(2000, 2050):
	t, isNorth = find_discrete(ts.tt(year, 1, 1), ts.tt(year + 1, 1, 1), north, epsilon=0.001 / 86400, num=12)
	latitudes, longitudes = place(t)
	for whole, fraction, ascending, latitude, longitude in zip(t.whole, t.tt_fraction, isNorth, latitudes, longitudes):
		# At a passage the latitude is zero, to the Moon's motion in latitude over the precision.
		assert abs(latitude) < 1e-9, (whole, fraction, latitude)
		events.append((float(whole), float(fraction), "ascending" if ascending else "descending", float(longitude)))
events.sort(key=lambda event: event[0] + event[1])

rows = [(whole, fraction, kind, longitude) for whole, fraction, kind, longitude in events]

out = [
	"//", "// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>", "// SPDX-License-Identifier: MIT", "//",
	"// Part of https://github.com/sbooth/Astronomia", "//", "",
	"// Generated by Scripts/Fixtures/lunar-node-fixtures.py. Do not edit.", "",
	"@testable import Astronomia", "",
	f"/// The Moon's passages through its nodes from 2000 to 2049 from Skyfield {skyfield.__version__} with DE421: the TT",
	"/// Julian Date, as a whole and a fraction, the node, and the apparent ecliptic longitude, in",
	"/// radians.",
	"let skyfieldLunarNodes: [(whole: Double, fraction: Double, kind: Moon.NodeEvent.Kind, longitude: Double)] = textFixture(\"SkyfieldLunarNodes\") { row in",
	"\t(row.double(), row.double(), row.value(), row.double())",
	"}", "",
]
open(sys.argv[2], "w").write("\n".join(out))
text_fixture.write(sys.argv[2], "skyfieldLunarNodes", "Scripts/Fixtures/lunar-node-fixtures.py", "whole fraction kind longitude", rows)
