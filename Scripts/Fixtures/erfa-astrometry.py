"""Writes ERFA's aberration and light deflection for chosen inputs as a Swift test fixture.

The inputs are random, from a fixed seed, so the output is the same on every run.

Requires:
  pyerfa 2.0.1.5 (ERFA 2.0.1)

Usage:
  Scripts/Fixtures/erfa-astrometry.py Tests/AstronomiaTests/Astrometry/ERFAAstrometry.swift
"""

import erfa, math, random, sys
if len(sys.argv) != 2:
	sys.exit("usage: Scripts/Fixtures/erfa-astrometry.py OUTPUT")

random.seed(2026)
def unit():
	while True:
		v = [random.uniform(-1, 1) for _ in range(3)]
		n = math.sqrt(sum(x * x for x in v))
		if 0.1 < n <= 1:
			return [x / n for x in v]
def f(v):
	return "[" + ", ".join(repr(float(x)) for x in v) + "]"
c = erfa.DC  # au/day
ab = []
for _ in range(12):
	p = unit()
	speed = random.uniform(25, 35) / 299792.458  # the Earth's speed, as a fraction of c
	v = [x * speed for x in unit()]
	s = random.uniform(0.98, 1.02)
	bm1 = math.sqrt(1 - sum(x * x for x in v))
	ppr = erfa.ab(p, v, s, bm1)
	ab.append(f"\t({f(p)}, {f([x * c for x in v])}, {s!r}, {f(ppr)}),")
ld = []
for bm, scale in ((1.0, 1.0), (0.00095435, 5.2), (0.00028574, 9.5)):
	for _ in range(6):
		p = unit()
		q = unit()
		e = unit()
		em = scale * random.uniform(0.9, 1.1)
		p1 = erfa.ld(bm, p, q, e, em, 1e-9)
		ld.append(f"\t({bm!r}, {f(p)}, {f(q)}, {f(e)}, {em!r}, {f(p1)}),")
out = [
	"//", "// SPDX-FileCopyrightText: 2026 Stephen F. Booth <contact@sbooth.dev>", "// SPDX-License-Identifier: MIT", "//",
	"// Part of https://github.com/sbooth/Astronomia", "//", "",
	"// Generated by Scripts/Fixtures/erfa-astrometry.py. Do not edit.", "",
	f"/// Aberration from ERFA {erfa.version.erfa_version}'s ab: the natural direction, the observer's barycentric",
	"/// velocity, in au/day, its distance from the Sun, in au, and the proper direction.",
	"let erfaAberration: [(direction: [Double], velocity: [Double], sunDistance: Double, aberrated: [Double])] = [",
] + ab + ["]", "",
	"/// Light deflection from ERFA's ld with a limiter of 1e-9: the body's mass in solar masses, the",
	"/// directions p, q, and e, the distance from the body to the observer, in au, and the",
	"/// deflected direction.",
	"let erfaDeflection: [(mass: Double, p: [Double], q: [Double], e: [Double], distance: Double, deflected: [Double])] = [",
] + ld + ["]", ""]
open(sys.argv[1], "w").write("\n".join(out))
